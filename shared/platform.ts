/** 每一关属于哪块大陆，由它的区域决定 */
export const NODES: Node[] = RAW_NODES.map(n => ({ ...n, d: area(n.a).d }));
/** 跨区域依赖：[前置, 后续] */
export const CROSS: [string, string][] = [['m3', 'v2'], ['m3', 'm4'], ['c2', 'c4'], ['v2', 'v3'], ['c1', 'e5'], ['m1', 'e6'], ['c5', 'g5'], ['m6', 'v7'], ['m7', 'g5'], ['g6', 'l9']];

export const node = (id: string) => NODES.find(n => n.id === id)!;
/** 前置关卡：同一区域上一层的关，加上跨区域依赖。跨区域依赖如果比这一关的年龄段还高，就不算（不能让小的等大的，比如幼儿园的关不能等小学的关） */
export function prereqs(n: Node): string[] {
  const p = NODES.filter(x => x.a === n.a && x.lv === n.lv - 1).map(x => x.id);
  for (const [a, b] of CROSS) {
    if (b !== n.id || p.includes(a)) continue;
    const pa = node(a).age;
    if (pa && ageIndex(pa) > ageIndex(n.age ?? 'br')) continue;   // 没标年龄的旧关都是幼儿园内容，按“幼小衔接”算
    p.push(a);
  }
  return p;
}
export type NodeState = 'done' | 'now' | 'lock';
/** 节点状态完全由“已点亮”的集合推出：前置都点亮了就开放。
 *  传了孩子的年龄段 band 时，比这个年龄段低的前置关当作已经会了（6 岁的孩子不用先过 3 岁的关，但可以回去玩） */
export function nodeState(id: string, done: ReadonlySet<string>, band?: AgeId): NodeState {
  if (done.has(id)) return 'done';
  const ok = (p: string) => done.has(p) || Boolean(band && node(p).age && ageIndex(node(p).age!) < ageIndex(band));
  return prereqs(node(id)).every(ok) ? 'now' : 'lock';
}
/** 这个年龄段的孩子能不能看到这一关：
 *  自己年龄段和更小的都能看到；同一区域里自己年龄段的关都点亮了，就能看到下一段的“挑战关”；
 *  但 6 岁前看不到 1～2 年级的关（教育部：幼儿园不提前教小学课程）。没标年龄的旧关卡都显示。 */
export function visibleFor(n: Node, band: AgeId, done: ReadonlySet<string>): boolean {
  if (!n.age) return true;
  const i = ageIndex(n.age), b = ageIndex(band);
  if (i <= b) return true;
  if (i !== b + 1 || (n.age === 'g1' && band !== 'g1')) return false;
  const mine = NODES.filter(x => x.a === n.a && x.age === band);
  return mine.length > 0 && mine.every(x => done.has(x.id));
}
/** 是不是“挑战关”（比孩子的年龄段高一段） */
export const isChallenge = (n: Node, band: AgeId) => Boolean(n.age && ageIndex(n.age) > ageIndex(band));
/** 点亮一个节点后，新开放的节点 */
export function newlyOpened(id: string, doneBefore: ReadonlySet<string>): Node[] {
  const after = new Set(doneBefore); after.add(id);
  return NODES.filter(n => !after.has(n.id) && nodeState(n.id, doneBefore) === 'lock' && nodeState(n.id, after) === 'now');
}
export const playable = (n: Node) => Boolean(n.module);

